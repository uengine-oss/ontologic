// 리허설 1 — 시스템 등록: CMMS 를 마법사로 등록하고, 스펙에 없는 API 를 수동으로 추가한다
import { chromium, STUDIO, sleep, log, pageText, nav } from './lib.mjs';
const OUT = 'rehearsal';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1280, height: 720 }, deviceScaleFactor: 1.5 });
const snap = async n => { await p.screenshot({ path: `${OUT}/${n}.png` }); log(n); };
await p.goto(STUDIO, { waitUntil: 'networkidle' });
await nav(p, '시스템 등록');
await p.locator('[data-testid=system-grid]').waitFor();
await sleep(1500);
await snap('r1-01-grid');
await p.locator('[data-testid=system-new]').click(); await sleep(800);
await p.locator('[data-testid=system-display-name]').fill('설비보전 CMMS');
await p.locator('[data-testid=system-name]').fill('mock-cmms');
await p.getByPlaceholder('설비보전 — 정비 작업지시').fill('설비보전 — 정비 작업지시 생성·취소');
await p.getByPlaceholder('설비보전팀').fill('설비보전팀');
await p.getByPlaceholder('maint-ops@example.com').fill('maint-ops@factory.example');
await p.getByPlaceholder('보전, 설비, P1').fill('보전, 설비, 작업지시');
await p.locator('.sr-icon-opt[title=CMMS]').click();
await snap('r1-02-step1');
await p.locator('[data-testid=system-next]').click(); await sleep(800);
await p.locator('[data-testid=system-spec-file]').setInputFiles('../onboarding/mock-cmms-openapi.json');
await sleep(1500);
await snap('r1-03-step2-spec');
await p.locator('[data-testid=system-next]').click(); await sleep(800);
await p.locator('[data-testid=system-env-url-0]').fill('http://localhost:8034');
await snap('r1-04-step3-env');
await p.locator('[data-testid=system-next]').click(); await sleep(800);
await p.locator('[data-testid=system-auth-kind]').selectOption('api_key');
await sleep(400);
await p.getByPlaceholder('X-Api-Key').fill('X-API-Key');
await p.getByPlaceholder('CMMS_API_KEY').fill('CMMS_API_KEY');
await snap('r1-05-step4-auth');
await p.locator('[data-testid=system-next]').click(); await sleep(800);
await p.getByPlaceholder('/health').fill('/health');
await snap('r1-06-step5-policy');
await p.locator('[data-testid=system-next]').click(); await sleep(800);
await p.locator('[data-testid=system-test]').click();
await p.locator('[data-testid=system-test-result]').waitFor({ timeout: 30000 }); await sleep(1000);
await snap('r1-07-step6-test');
console.log((await p.locator('[data-testid=system-test-result]').innerText()).slice(0, 600));
await p.locator('[data-testid=system-submit]').click();
await p.locator('[data-testid=system-detail]').waitFor({ timeout: 30000 }); await sleep(1500);
await snap('r1-08-detail');
await p.locator('[data-testid=operation-add-open]').click(); await sleep(600);
await p.locator('[data-testid=operation-id]').fill('getWorkOrder');
await p.locator('[data-testid=operation-method]').selectOption('GET');
await p.locator('[data-testid=operation-path]').fill('/work-orders/{id}');
await p.getByPlaceholder('작업지시 한 건 조회').fill('작업지시 한 건 조회 (스펙에 없는 API)');
await p.getByRole('button', { name: '자동 추가' }).click(); await sleep(500);
await snap('r1-09-opform');
await p.locator('[data-testid=operation-submit]').click(); await sleep(2000);
await snap('r1-10-op-added');
const t = await pageText(p);
console.log('ops visible:', ['createWorkOrder', 'cancelWorkOrder', 'getWorkOrder'].map(x => `${x}:${t.includes(x)}`).join(' '));
await b.close();
